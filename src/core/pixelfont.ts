const ALIAS: Record<string, string> = { '’': "'", '‘': "'", '“': '"', '”': '"', '–': '-', '—': '-' };

/** Glyph for a character: accented letters fall back to their plain letter, unknown ones to "?". */
function glyph(ch: string): string[] {
  ch = ALIAS[ch] ?? ch;
  return G[ch] ?? G[ch.normalize('NFD').replace(/[̀-ͯ]/g, '')] ?? G['?'];
}

/** Width of text in font pixels (1 pixel gap between letters). */
export function textWidth(text: string) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}

export const FONT_HEIGHT = 7;

/** Draw text with its top-left at (x, y); `px` = how big one font pixel is on screen. Returns the width drawn. */
export function drawPixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, px: number) {
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    for (let r = 0; r < g.length; r++) {
      const row = g[r];
      for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(cx + c * px, y + r * px, px, px);
    }
    cx += (g[0].length + 1) * px;
  }
  return cx - x - px;
}

/** Break text into lines no wider than `maxW` font pixels. */
export function wrapPixelText(text: string, maxW: number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    const next = line ? `${line} ${word}` : word;
    if (line && textWidth(next) > maxW) { lines.push(line); line = word; } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
